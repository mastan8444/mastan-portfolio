import { useState, useRef, useEffect } from "react";
import { Message } from "../types";
import { Bot, User, Send, Sparkles, AlertCircle, HelpCircle, Loader2 } from "lucide-react";
import { motion, AnimatePresence } from "motion/react";

const SYSTEM_WELCOME = `Hello! I am **Shaik's AI Copilot**, an agentic virtual assistant trained on Shaik Mastan Saheb's professional resume, project designs, and technical credentials. 

I'm ready to answer any questions about Shaik's skills, experience, or projects. You can select one of the quick prompts below or write your own custom question!`;

const QUICK_PROMPTS = [
  "Summarize Shaik's AI Internship at Calibo",
  "How does his AI-Powered PPT Generator compile slides?",
  "What are Shaik's core competencies and languages?",
  "Tell me about his academic records & achievements",
  "Generate a mock pitch: Why hire Shaik?"
];

